CREATE TABLE IF NOT EXISTS chat_users (
  username_key VARCHAR(24) PRIMARY KEY,
  username VARCHAR(24) NOT NULL,
  joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
  cognito_sub VARCHAR(128)
);

ALTER TABLE chat_users ADD COLUMN IF NOT EXISTS cognito_sub VARCHAR(128);
CREATE UNIQUE INDEX IF NOT EXISTS chat_users_cognito_sub_idx ON chat_users (cognito_sub);

CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author VARCHAR(24) NOT NULL,
  message_text VARCHAR(2000) NOT NULL,
  file_id VARCHAR(36),
  file_name VARCHAR(512),
  file_content_type VARCHAR(255),
  file_size BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
